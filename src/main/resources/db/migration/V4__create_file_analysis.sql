CREATE TABLE file_analysis (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    file_record_id BIGINT NOT NULL REFERENCES file_record(id),
    source_sha256 VARCHAR(64) NOT NULL,
    ocr_enabled BOOLEAN NOT NULL,
    visual_enabled BOOLEAN NOT NULL,
    result_json TEXT NOT NULL,
    analyzed_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_file_analysis_options UNIQUE (file_record_id, ocr_enabled, visual_enabled),
    CONSTRAINT ck_file_analysis_sha CHECK (source_sha256 ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_file_analysis_step CHECK (ocr_enabled OR visual_enabled)
);

CREATE INDEX ix_file_analysis_latest ON file_analysis(file_record_id, analyzed_at DESC);
