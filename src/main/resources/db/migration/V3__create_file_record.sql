CREATE TABLE file_record (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    allowed_root_id BIGINT NOT NULL,
    relative_path VARCHAR(2048) NOT NULL,
    original_name VARCHAR(255) NOT NULL,
    extension VARCHAR(16) NOT NULL,

    size_bytes BIGINT NOT NULL,
    last_modified_at TIMESTAMP WITH TIME ZONE NOT NULL,
    sha256 VARCHAR(64) NOT NULL,

    first_discovered_at TIMESTAMP WITH TIME ZONE NOT NULL,
    last_seen_at TIMESTAMP WITH TIME ZONE NOT NULL,

    CONSTRAINT fk_file_record_allowed_root
        FOREIGN KEY (allowed_root_id)
        REFERENCES allowed_root(id),

    CONSTRAINT uk_file_record_location
        UNIQUE (allowed_root_id, relative_path),

    CONSTRAINT ck_file_record_size_not_negative
        CHECK (size_bytes >= 0),

    CONSTRAINT ck_file_record_sha256
        CHECK (sha256 ~ '^[0-9a-f]{64}$')
);

CREATE INDEX ix_file_record_sha256
    ON file_record(sha256);