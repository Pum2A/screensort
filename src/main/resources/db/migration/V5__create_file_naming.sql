CREATE TABLE file_naming (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    file_record_id BIGINT NOT NULL REFERENCES file_record(id),
    analysis_id BIGINT NOT NULL REFERENCES file_analysis(id),
    source_sha256 VARCHAR(64) NOT NULL,
    approved_name VARCHAR(255) NOT NULL,
    approved_at TIMESTAMP WITH TIME ZONE NOT NULL,
    revision BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uk_file_naming_file UNIQUE (file_record_id),
    CONSTRAINT ck_file_naming_sha CHECK (source_sha256 ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_file_naming_name CHECK (length(btrim(approved_name)) > 0),
    CONSTRAINT ck_file_naming_revision CHECK (revision >= 0)
);
