CREATE TABLE allowed_root (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    canonical_path VARCHAR(2048) NOT NULL,
    recursive_scan BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_allowed_root_canonical_path UNIQUE (canonical_path),
    CONSTRAINT ck_allowed_root_canonical_path_not_blank CHECK (BTRIM(canonical_path) <> '')
);
